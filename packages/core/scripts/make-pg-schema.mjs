// Writes src/db/schema.pg.ts (PostgreSQL) from src/db/schema.ts (SQLite), so the two always have the
// same tables, columns and TypeScript types. Run by `npm run db:generate`; CI checks it is up to date.
//   integer ids (autoincrement) -> identity columns     integer(mode: boolean) -> boolean
//   real -> double precision                             text(mode: json) -> jsonb
//   ISO text timestamps keep the same format via to_char(now())
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/db");
let s = fs.readFileSync(path.join(dir, "schema.ts"), "utf8");
const rules = [
  [/^\/\*\*[\s\S]*?\*\/\n/, "/**\n * PostgreSQL version of ./schema.ts. GENERATED by packages/core/scripts/make-pg-schema.mjs: edit schema.ts, then run `npm run db:generate`.\n */\n"],
  [/import \{([^}]*)\} from "drizzle-orm\/sqlite-core";/, 'import { boolean, doublePrecision, index, integer, jsonb, pgTable, primaryKey, text, uniqueIndex } from "drizzle-orm/pg-core";'],
  [/sqliteTable\(/g, "pgTable("],
  [/integer\("id"\)\.primaryKey\(\{ autoIncrement: true \}\)/g, 'integer("id").primaryKey().generatedByDefaultAsIdentity()'],
  [/integer\(("[a-z_]+"), \{ mode: "boolean" \}\)/g, "boolean($1)"],
  [/\breal\(/g, "doublePrecision("],
  [/text\(("[a-z_]+"), \{ mode: "json" \}\)/g, "jsonb($1)"],
  [/sql`\(strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)\)`/g, "sql`to_char(now() at time zone 'utc', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')`"],
];
for (const [re, to] of rules) {
  const before = s;
  s = s.replace(re, to);
  if (before === s && !(re.flags.includes("g") && !re.test(before))) throw new Error(`make-pg-schema: rule did not apply: ${re}`);
}
if (/sqlite/i.test(s.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, ""))) throw new Error("make-pg-schema: something SQLite-specific is left; extend the rules");
const out = path.join(dir, "schema.pg.ts");
const check = process.argv.includes("--check");
if (check) {
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== s) { console.error("schema.pg.ts is out of date: run npm run db:generate"); process.exit(1); }
  console.log("schema.pg.ts is up to date");
} else { fs.writeFileSync(out, s); console.log("wrote", path.relative(process.cwd(), out)); }
